const CATALOG: Record<AppLocale, Pack> = { zh, en, ja, ko, es, pt, de, fr, it };

let current: AppLocale = "zh";

export function getLocale(): AppLocale {
  return current;
}

export function setLocale(v: unknown): AppLocale {
  current = normalizeLocale(v);
  return current;
}

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  let out = s;
  for (const [k, val] of Object.entries(vars)) {
    out = out.split(`{${k}}`).join(String(val));
  }
  return out;
}

export function tx(
  locale: string | undefined,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const loc = normalizeLocale(locale);
  const pack = CATALOG[loc] || zh;
  const s = pack[key] || en[key] || zh[key] || key;
  return interpolate(s, vars);
}

export function t(key: string, vars?: Record<string, string | number>): string {
  return tx(current, key, vars);
}

export function applyDom(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key) el.innerHTML = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.title = t(key);
  });
  root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach(
    (el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.placeholder = t(key);
    },
  );
  if (typeof document !== "undefined") {
    document.documentElement.lang = htmlLang(current);
  }
}
