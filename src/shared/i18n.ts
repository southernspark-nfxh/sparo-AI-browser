/** UI locales for the store edition. Fallback: zh → en → key. */

export const APP_LOCALES = ["zh", "en", "ja", "ko", "es", "pt", "de", "fr", "it"] as const;
export type AppLocale = (typeof APP_LOCALES)[number];

export const LOCALE_META: { id: AppLocale; native: string }[] = [
  { id: "zh", native: "中文" },
  { id: "en", native: "English" },
  { id: "ja", native: "日本語" },
  { id: "ko", native: "한국어" },
  { id: "es", native: "Español" },
  { id: "pt", native: "Português" },
  { id: "de", native: "Deutsch" },
  { id: "fr", native: "Français" },
  { id: "it", native: "Italiano" },
];

const HTML_LANG: Record<AppLocale, string> = {
  zh: "zh-CN",
  en: "en",
  ja: "ja",
  ko: "ko",
  es: "es",
  pt: "pt",
  de: "de",
  fr: "fr",
  it: "it",
};

export function isAppLocale(v: unknown): v is AppLocale {
  return typeof v === "string" && (APP_LOCALES as readonly string[]).includes(v);
}

export function detectLocale(raw?: string): AppLocale {
  const s = String(raw || "").toLowerCase().replace("_", "-");
  if (s.startsWith("zh")) return "zh";
  if (s.startsWith("en")) return "en";
  if (s.startsWith("ja")) return "ja";
  if (s.startsWith("ko")) return "ko";
  if (s.startsWith("es")) return "es";
  if (s.startsWith("pt")) return "pt";
  if (s.startsWith("de")) return "de";
  if (s.startsWith("fr")) return "fr";
  if (s.startsWith("it")) return "it";
  return "en";
}

export function normalizeLocale(v: unknown): AppLocale {
  if (isAppLocale(v)) return v;
  return detectLocale(typeof v === "string" ? v : "");
}

export function htmlLang(locale: AppLocale): string {
  return HTML_LANG[locale];
}

